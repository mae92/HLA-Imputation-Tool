# =====================================================================================
# BUILD LOOKUP DICTIONARY
# =====================================================================================


lookup = {}

for gene, antigen, mol in REFERENCE_DATA:
    if mol == "" or mol is None:
        continue

    # Normalize mol (remove any ":xx" if present)
    mol_clean = str(mol).split(":")[0]

    key = (gene, mol_clean)

    if key not in lookup:
        lookup[key] = []

    lookup[key].append(antigen)


# =====================================================================================
# PARSING FUNCTION
# =====================================================================================

def convert_allele(allele):
    if not allele or allele.strip() == "":
        return ""

    allele = allele.strip()

    # Extract gene and numeric part
    match = re.match(r"([A-Z0-9]+)\*(\d+)", allele)
    if not match:
        return allele  # fallback

    gene = match.group(1)
    number = match.group(2).lstrip("0")  # remove leading zeros

    key = (gene, number)

    if key not in lookup:
        return ""  # or keep original if preferred

    return random.choice(lookup[key])


# =====================================================================================
# MAIN PROCESSING
# =====================================================================================

def process_file(input_file):
    output_file = os.path.splitext(input_file)[0] + "_sero.csv"

    with open(input_file, newline="", encoding="utf-8") as infile:
        reader = csv.reader(infile)
        headers = next(reader)

        with open(output_file, "w", newline="", encoding="utf-8") as outfile:
            writer = csv.writer(outfile)
            writer.writerow(headers)

            for row in reader:
                new_row = []

                for col in row:
                    new_row.append(convert_allele(col))

                writer.writerow(new_row)

    print(f"✅ Conversion complete: {output_file}")


